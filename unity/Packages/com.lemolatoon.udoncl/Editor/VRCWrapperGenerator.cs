using System;
using System.Collections.Generic;
using System.Text;
using UnityEngine;

namespace Lemolatoon.Udoncl.Editor
{
    public static class VRCWrapperGenerator
    {
        public static string GenerateFromJson(
            string manifestJson,
            string namespaceName,
            string className
        )
        {
            if (string.IsNullOrWhiteSpace(manifestJson))
                throw new ArgumentException("Manifest JSON is empty.", nameof(manifestJson));
            UdonclManifest manifest = JsonUtility.FromJson<UdonclManifest>(manifestJson);
            return Generate(manifest, namespaceName, className);
        }

        internal static string Generate(
            UdonclManifest manifest,
            string namespaceName,
            string className
        )
        {
            if (manifest == null)
                throw new ArgumentNullException(nameof(manifest));
            RequireIdentifier(namespaceName, nameof(namespaceName), allowDots: true);
            RequireIdentifier(className, nameof(className), allowDots: false);
            if (manifest.physical_export_abi != "udonsharp-worlds-sdk-3.10.5")
                throw new ArgumentException("Unsupported physical export ABI.", nameof(manifest));

            ExportInfo[] exports =
                manifest.exports == null
                    ? Array.Empty<ExportInfo>()
                    : (ExportInfo[])manifest.exports.Clone();
            if (exports.Length == 0)
                throw new ArgumentException("Typed wrapper requires at least one export.");
            Array.Sort(exports, (left, right) => left.id.CompareTo(right.id));
            bool hasAsyncExports = Array.Exists(exports, export => export != null && export.async);
            AsyncCommandInfo asyncCommands = manifest.program?.async_commands;
            if (hasAsyncExports)
                ValidateAsyncCommands(asyncCommands);
            bool staticAsyncBackend =
                hasAsyncExports
                && !string.IsNullOrEmpty(asyncCommands.pending_object_slot)
                && !string.IsNullOrEmpty(asyncCommands.completion_object_slot)
                && !string.IsNullOrEmpty(asyncCommands.completion_event);
            HashSet<string> publicNames = new HashSet<string>(StringComparer.Ordinal);
            StringBuilder source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using UdonSharp;");
            source.AppendLine("using UnityEngine;");
            source.AppendLine("using VRC.SDK3.Rendering;");
            source.AppendLine("using VRC.SDKBase;");
            source.AppendLine("using VRC.Udon;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine();
            source.AppendLine("{");
            source
                .Append("    public sealed class ")
                .Append(className)
                .AppendLine(" : UdonSharpBehaviour");
            source.AppendLine("    {");
            source.AppendLine("        public const int StatusSuccess = 0;");
            source.AppendLine("        public const int StatusNotInitialized = -1;");
            source.AppendLine("        public const int StatusBusy = -2;");
            source.AppendLine("        public const int StatusInvalidArgument = -3;");
            source.AppendLine("        public const int StatusAbiMismatch = -4;");
            source.AppendLine("        public const int StatusExecutionFailure = -5;");
            source.AppendLine("        public const int StatusDisposed = -6;");
            source.AppendLine();
            source.AppendLine("        [SerializeField] private UdonBehaviour program;");
            DeviceBufferInfo[] buffers =
                manifest.device == null || manifest.device.buffers == null
                    ? Array.Empty<DeviceBufferInfo>()
                    : manifest.device.buffers;
            if (buffers.Length != 0)
            {
                ValidateDeviceBuffers(buffers);
                source.AppendLine("        [SerializeField] private int[] deviceBufferIds;");
                source.AppendLine(
                    "        [SerializeField] private int[] deviceBufferLogicalBytes;"
                );
                source.AppendLine(
                    "        [SerializeField] private RenderTexture[] deviceBuffers;"
                );
                source.AppendLine("        [SerializeField] private Material bufferCopyMaterial;");
                source.AppendLine("        private Texture2D[] uploadTextures;");
                source.AppendLine("        private int pendingReadbackIndex;");
                source.AppendLine("        private float[] pendingFloatReadback;");
                source.AppendLine("        private int[] pendingIntReadback;");
                source.AppendLine("        private UdonSharpBehaviour pendingReadbackReceiver;");
                source.AppendLine("        private string pendingReadbackEvent;");
                source.AppendLine("        private int lastReadbackStatus;");
                source.AppendLine("        private int pendingReadbackGeneration;");
            }
            if (hasAsyncExports)
            {
                if (buffers.Length == 0)
                    throw new ArgumentException(
                        "Async exports require generated Device buffers.",
                        nameof(manifest)
                    );
                source.AppendLine("        private UdonSharpBehaviour pendingAsyncReceiver;");
                source.AppendLine("        private string pendingAsyncCompletionEvent;");
                source.AppendLine("        private string pendingAsyncUdonEvent;");
                source.AppendLine("        private int pendingAsyncExportId;");
                source.AppendLine("        private int pendingAsyncGeneration;");
                source.AppendLine("        private int lastAsyncExportId;");
                source.AppendLine("        private int lastAsyncStatus = StatusNotInitialized;");
                source.AppendLine("        private int asyncCommandReadbackMode;");
                source.AppendLine("        private int asyncCommandBufferIndex;");
                source.AppendLine("        private int asyncCommandOffsetWords;");
                source.AppendLine("        private int asyncCommandSizeWords;");
                source.AppendLine("        private int asyncCommandPointerBytes;");
                source.AppendLine("        private int[] asyncCommandHeap;");
                if (staticAsyncBackend)
                {
                    source.AppendLine("        private int pendingAsyncObject;");
                    source.AppendLine("        private int pendingAsyncCompletionStatus;");
                }
            }
            source.AppendLine("        private int generation = 1;");
            source.AppendLine("        private bool busy;");
            source.AppendLine("        private bool readbackBusy;");
            source.AppendLine("        private bool disposed;");
            source.AppendLine();
            source.AppendLine("        public int TryBindProgram(UdonBehaviour value)");
            source.AppendLine("        {");
            source.AppendLine("            if (value == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine(
                "            generation = generation == int.MaxValue ? 1 : generation + 1;"
            );
            source.AppendLine("            program = value;");
            source.AppendLine("            busy = false;");
            source.AppendLine("            disposed = false;");
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public bool IsInitialized()");
            source.AppendLine("        {");
            source.AppendLine("            return program != null && !disposed;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public int TryDispose()");
            source.AppendLine("        {");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusSuccess;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine(
                "            generation = generation == int.MaxValue ? 1 : generation + 1;"
            );
            source.AppendLine("            disposed = true;");
            source.AppendLine("            program = null;");
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");

            if (buffers.Length != 0)
                EmitBufferTransfers(source, "public", hasAsyncExports);

            HashSet<string> generatedMethodNames = new HashSet<string>(StringComparer.Ordinal)
            {
                "GetLastReadbackStatus",
                "IsInitialized",
                "StartReadFloatBuffer",
                "StartReadIntBuffer",
                "TryBindProgram",
                "TryDispose",
                "TryWriteFloatBuffer",
                "TryWriteIntBuffer",
            };
            if (buffers.Length != 0)
                EmitNamedBufferTransfers(source, buffers, generatedMethodNames);

            foreach (ExportInfo export in exports)
            {
                ValidateExport(export, publicNames);
                string methodName = (export.async ? "Start" : "Try") + export.public_name;
                if (!generatedMethodNames.Add(methodName))
                    throw new ArgumentException("Generated U# method names collide.");
                if (export.async)
                    EmitAsyncExport(source, export, asyncCommands, staticAsyncBackend);
                else
                    EmitExport(source, export);
            }

            if (hasAsyncExports)
                EmitAsyncCommandRuntime(source, exports, asyncCommands, staticAsyncBackend);

            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        private static void EmitBufferTransfers(
            StringBuilder source,
            string visibility,
            bool asyncCommands
        )
        {
            source.AppendLine();
            source.AppendLine("        private int FindDeviceBuffer(int bufferId)");
            source.AppendLine("        {");
            source.AppendLine(
                "            if (deviceBufferIds == null || deviceBuffers == null || deviceBufferLogicalBytes == null)"
            );
            source.AppendLine("                return -1;");
            source.AppendLine(
                "            for (int index = 0; index < deviceBufferIds.Length; ++index)"
            );
            source.AppendLine("                if (deviceBufferIds[index] == bufferId)");
            source.AppendLine("                    return index;");
            source.AppendLine("            return -1;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private int ValidateTransfer(int bufferId, int words)");
            source.AppendLine("        {");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusDisposed;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            if (program == null || bufferCopyMaterial == null)");
            source.AppendLine("                return StatusNotInitialized;");
            source.AppendLine("            int index = FindDeviceBuffer(bufferId);");
            source.AppendLine(
                "            if (index < 0 || deviceBuffers[index] == null || words < 0 || words * 4 != deviceBufferLogicalBytes[index])"
            );
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            return index;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private Color32 PackWord(int word)");
            source.AppendLine("        {");
            source.AppendLine(
                "            return new Color32((byte)(word & 255), (byte)((word >> 8) & 255), (byte)((word >> 16) & 255), (byte)((word >> 24) & 255));"
            );
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private int UnpackWord(Color32 pixel)");
            source.AppendLine("        {");
            source.AppendLine(
                "            return pixel.r | (pixel.g << 8) | (pixel.b << 16) | (pixel.a << 24);"
            );
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private int UploadWords(int index, Color32[] pixels)");
            source.AppendLine("        {");
            source.AppendLine("            if (uploadTextures == null)");
            source.AppendLine(
                "                uploadTextures = new Texture2D[deviceBuffers.Length];"
            );
            source.AppendLine("            RenderTexture destination = deviceBuffers[index];");
            source.AppendLine("            Texture2D staging = uploadTextures[index];");
            source.AppendLine("            if (staging == null)");
            source.AppendLine("            {");
            source.AppendLine(
                "                staging = new Texture2D(destination.width, destination.height, TextureFormat.RGBA32, false, true);"
            );
            source.AppendLine("                uploadTextures[index] = staging;");
            source.AppendLine("            }");
            source.AppendLine("            staging.SetPixels32(pixels);");
            source.AppendLine("            staging.Apply(false, false);");
            source.AppendLine(
                "            VRCGraphics.Blit(staging, destination, bufferCopyMaterial);"
            );
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        " + visibility + " int TryWriteFloatBuffer(int bufferId, float[] source)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (source == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            int index = ValidateTransfer(bufferId, source.Length);");
            source.AppendLine("            if (index < 0)");
            source.AppendLine("                return index;");
            source.AppendLine(
                "            Color32[] pixels = new Color32[deviceBuffers[index].width * deviceBuffers[index].height];"
            );
            source.AppendLine("            for (int word = 0; word < source.Length; ++word)");
            source.AppendLine(
                "                pixels[word] = PackWord(System.BitConverter.SingleToInt32Bits(source[word]));"
            );
            source.AppendLine("            return UploadWords(index, pixels);");
            source.AppendLine("        }");
            source.AppendLine();
            source
                .Append("        ")
                .Append(visibility)
                .AppendLine(" int TryWriteIntBuffer(int bufferId, int[] source)");
            source.AppendLine("        {");
            source.AppendLine("            if (source == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            int index = ValidateTransfer(bufferId, source.Length);");
            source.AppendLine("            if (index < 0)");
            source.AppendLine("                return index;");
            source.AppendLine(
                "            Color32[] pixels = new Color32[deviceBuffers[index].width * deviceBuffers[index].height];"
            );
            source.AppendLine("            for (int word = 0; word < source.Length; ++word)");
            source.AppendLine("                pixels[word] = PackWord(source[word]);");
            source.AppendLine("            return UploadWords(index, pixels);");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        private int StartReadback(int bufferId, int words, UdonSharpBehaviour receiver, string completionEvent)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine(
                "            if (receiver == null || string.IsNullOrEmpty(completionEvent))"
            );
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            int index = ValidateTransfer(bufferId, words);");
            source.AppendLine("            if (index < 0)");
            source.AppendLine("                return index;");
            source.AppendLine("            readbackBusy = true;");
            source.AppendLine("            pendingReadbackIndex = index;");
            source.AppendLine("            pendingReadbackReceiver = receiver;");
            source.AppendLine("            pendingReadbackEvent = completionEvent;");
            source.AppendLine("            pendingReadbackGeneration = generation;");
            source.AppendLine("            lastReadbackStatus = StatusBusy;");
            source.AppendLine(
                "            VRCAsyncGPUReadback.Request(deviceBuffers[index], 0, TextureFormat.RGBA32, this);"
            );
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        "
                    + visibility
                    + " int StartReadFloatBuffer(int bufferId, float[] destination, UdonSharpBehaviour receiver, string completionEvent)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (destination == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            if (readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            pendingFloatReadback = destination;");
            source.AppendLine("            pendingIntReadback = null;");
            source.AppendLine(
                "            int status = StartReadback(bufferId, destination.Length, receiver, completionEvent);"
            );
            source.AppendLine("            if (status != StatusSuccess)");
            source.AppendLine("                pendingFloatReadback = null;");
            source.AppendLine("            return status;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        "
                    + visibility
                    + " int StartReadIntBuffer(int bufferId, int[] destination, UdonSharpBehaviour receiver, string completionEvent)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (destination == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            if (readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            pendingIntReadback = destination;");
            source.AppendLine("            pendingFloatReadback = null;");
            source.AppendLine(
                "            int status = StartReadback(bufferId, destination.Length, receiver, completionEvent);"
            );
            source.AppendLine("            if (status != StatusSuccess)");
            source.AppendLine("                pendingIntReadback = null;");
            source.AppendLine("            return status;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public int GetLastReadbackStatus()");
            source.AppendLine("        {");
            source.AppendLine("            return lastReadbackStatus;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        public override void OnAsyncGpuReadbackComplete(VRCAsyncGPUReadbackRequest request)"
            );
            source.AppendLine("        {");
            if (asyncCommands)
            {
                source.AppendLine("            if (asyncCommandReadbackMode != 0)");
                source.AppendLine("            {");
                source.AppendLine("                CompleteAsyncCommandReadback(request);");
                source.AppendLine("                return;");
                source.AppendLine("            }");
            }
            source.AppendLine("            if (!readbackBusy)");
            source.AppendLine("                return;");
            source.AppendLine("            if (pendingReadbackGeneration != generation)");
            source.AppendLine("            {");
            source.AppendLine("                readbackBusy = false;");
            source.AppendLine("                pendingFloatReadback = null;");
            source.AppendLine("                pendingIntReadback = null;");
            source.AppendLine("                pendingReadbackReceiver = null;");
            source.AppendLine("                pendingReadbackEvent = null;");
            source.AppendLine("                pendingReadbackGeneration = 0;");
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source.AppendLine(
                "            RenderTexture source = deviceBuffers[pendingReadbackIndex];"
            );
            source.AppendLine(
                "            Color32[] pixels = new Color32[source.width * source.height];"
            );
            source.AppendLine("            bool success = request.TryGetData(pixels, 0);");
            source.AppendLine("            if (success)");
            source.AppendLine("            {");
            source.AppendLine(
                "                int words = pendingFloatReadback != null ? pendingFloatReadback.Length : pendingIntReadback.Length;"
            );
            source.AppendLine("                for (int word = 0; word < words; ++word)");
            source.AppendLine("                {");
            source.AppendLine("                    int bits = UnpackWord(pixels[word]);");
            source.AppendLine("                    if (pendingFloatReadback != null)");
            source.AppendLine(
                "                        pendingFloatReadback[word] = System.BitConverter.Int32BitsToSingle(bits);"
            );
            source.AppendLine("                    else");
            source.AppendLine("                        pendingIntReadback[word] = bits;");
            source.AppendLine("                }");
            source.AppendLine("            }");
            source.AppendLine(
                "            lastReadbackStatus = success ? StatusSuccess : StatusExecutionFailure;"
            );
            source.AppendLine("            readbackBusy = false;");
            source.AppendLine("            pendingFloatReadback = null;");
            source.AppendLine("            pendingIntReadback = null;");
            source.AppendLine("            UdonSharpBehaviour receiver = pendingReadbackReceiver;");
            source.AppendLine("            string completionEvent = pendingReadbackEvent;");
            source.AppendLine("            pendingReadbackReceiver = null;");
            source.AppendLine("            pendingReadbackEvent = null;");
            source.AppendLine("            pendingReadbackGeneration = 0;");
            source.AppendLine("            if (receiver != null)");
            source.AppendLine("                receiver.SendCustomEvent(completionEvent);");
            source.AppendLine("        }");
        }

        private static void EmitNamedBufferTransfers(
            StringBuilder source,
            DeviceBufferInfo[] buffers,
            HashSet<string> generatedMethodNames
        )
        {
            for (int index = 0; index < buffers.Length; ++index)
            {
                DeviceBufferInfo buffer = buffers[index];
                if (string.IsNullOrEmpty(buffer.element_type))
                    continue;
                string suffix = PublicIoName(buffer.name, index);
                if (buffer.public_access == "input")
                {
                    string method = "TryWrite" + suffix;
                    if (!generatedMethodNames.Add(method))
                        throw new ArgumentException("Generated U# buffer method names collide.");
                    source.AppendLine();
                    source
                        .Append("        public int ")
                        .Append(method)
                        .Append('(')
                        .Append(buffer.element_type == "float32" ? "float[]" : "int[]")
                        .AppendLine(" source)");
                    source.AppendLine("        {");
                    source
                        .Append("            return ")
                        .Append(
                            buffer.element_type == "float32"
                                ? "TryWriteFloatBuffer("
                                : "TryWriteIntBuffer("
                        )
                        .Append(buffer.id)
                        .AppendLine(", source);");
                    source.AppendLine("        }");
                }
                else
                {
                    string method = "StartRead" + suffix;
                    if (!generatedMethodNames.Add(method))
                        throw new ArgumentException("Generated U# buffer method names collide.");
                    source.AppendLine();
                    source
                        .Append("        public int ")
                        .Append(method)
                        .Append('(')
                        .Append(buffer.element_type == "float32" ? "float[]" : "int[]")
                        .AppendLine(
                            " destination, UdonSharpBehaviour receiver, string completionEvent)"
                        );
                    source.AppendLine("        {");
                    source
                        .Append("            return ")
                        .Append(
                            buffer.element_type == "float32"
                                ? "StartReadFloatBuffer("
                                : "StartReadIntBuffer("
                        )
                        .Append(buffer.id)
                        .AppendLine(", destination, receiver, completionEvent);");
                    source.AppendLine("        }");
                }
            }
        }

        private static void ValidateDeviceBuffers(DeviceBufferInfo[] buffers)
        {
            HashSet<int> ids = new HashSet<int>();
            foreach (DeviceBufferInfo buffer in buffers)
                if (
                    buffer == null
                    || buffer.id < 0
                    || !ids.Add(buffer.id)
                    || buffer.logical_bytes < 0
                    || buffer.logical_bytes % 4 != 0
                    || buffer.width <= 0
                    || buffer.height <= 0
                    || buffer.width * buffer.height * 4 < buffer.logical_bytes
                    || buffer.format != "rgba8_unorm"
                    || (
                        !string.IsNullOrEmpty(buffer.element_type)
                        && (
                            (buffer.element_type != "float32" && buffer.element_type != "int32")
                            || (buffer.public_access != "input" && buffer.public_access != "output")
                        )
                    )
                    || (
                        string.IsNullOrEmpty(buffer.element_type)
                        != string.IsNullOrEmpty(buffer.public_access)
                    )
                )
                    throw new ArgumentException(
                        "Unsupported generated Device buffer transfer ABI."
                    );
        }

        private static string PublicIoName(string name, int index)
        {
            StringBuilder result = new StringBuilder();
            bool capitalize = true;
            foreach (char character in name)
            {
                if (!char.IsLetterOrDigit(character))
                {
                    capitalize = true;
                    continue;
                }
                if (result.Length == 0 && char.IsDigit(character))
                    result.Append("Value");
                result.Append(capitalize ? char.ToUpperInvariant(character) : character);
                capitalize = false;
            }
            if (result.Length == 0)
                result.Append("Value").Append(index);
            return result.ToString();
        }

        public static string BindingClassName(string programName)
        {
            if (string.IsNullOrEmpty(programName))
                throw new ArgumentException("Program name is empty.", nameof(programName));
            StringBuilder result = new StringBuilder("Udoncl");
            bool capitalize = true;
            foreach (char character in programName)
            {
                if (!char.IsLetterOrDigit(character))
                {
                    capitalize = true;
                    continue;
                }
                result.Append(capitalize ? char.ToUpperInvariant(character) : character);
                capitalize = false;
            }
            return result + "Binding";
        }

        private static void EmitExport(StringBuilder source, ExportInfo export)
        {
            ExportParameterInfo[] parameters =
                export.parameters ?? Array.Empty<ExportParameterInfo>();
            string resultType = HasResult(export) ? CSharpType(export.result.kind) : null;
            source.AppendLine();
            source.Append("        public int Try").Append(export.public_name).Append('(');
            for (int index = 0; index < parameters.Length; ++index)
            {
                if (index != 0)
                    source.Append(", ");
                source
                    .Append(CSharpType(parameters[index].kind))
                    .Append(' ')
                    .Append(parameters[index].name);
            }
            if (resultType != null)
            {
                if (parameters.Length != 0)
                    source.Append(", ");
                source.Append("out ").Append(resultType).Append(" result");
            }
            source.AppendLine(")");
            source.AppendLine("        {");
            if (resultType != null)
                source.AppendLine("            result = default;");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusDisposed;");
            source.AppendLine("            if (program == null)");
            source.AppendLine("                return StatusNotInitialized;");
            source.AppendLine("            if (busy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            busy = true;");
            for (int index = 0; index < parameters.Length; ++index)
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(parameters[index].heap_slot))
                    .Append("\", ")
                    .Append(parameters[index].name)
                    .AppendLine(");");
            source
                .Append("            program.SendCustomEvent(\"")
                .Append(Escape(export.udon_event))
                .AppendLine("\");");
            source
                .Append("            object rawStatus = program.GetProgramVariable(\"")
                .Append(Escape(export.status_slot))
                .AppendLine("\");");
            source.AppendLine("            if (rawStatus == null)");
            source.AppendLine("            {");
            source.AppendLine("                busy = false;");
            source.AppendLine("                return StatusAbiMismatch;");
            source.AppendLine("            }");
            source.AppendLine("            int status = (int)rawStatus;");
            source.AppendLine("            busy = false;");
            source.AppendLine("            if (status != StatusSuccess)");
            source.AppendLine("                return status;");
            if (resultType != null)
            {
                source
                    .Append("            object rawResult = program.GetProgramVariable(\"")
                    .Append(Escape(export.result.heap_slot))
                    .AppendLine("\");");
                source.AppendLine("            if (rawResult == null)");
                source.AppendLine("                return StatusAbiMismatch;");
                source
                    .Append("            result = (")
                    .Append(resultType)
                    .AppendLine(")rawResult;");
            }
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
        }

        private static void EmitAsyncExport(
            StringBuilder source,
            ExportInfo export,
            AsyncCommandInfo commands,
            bool staticAsyncBackend
        )
        {
            ExportParameterInfo[] parameters =
                export.parameters ?? Array.Empty<ExportParameterInfo>();
            string resultType = HasResult(export) ? CSharpType(export.result.kind) : null;
            if (resultType != null)
                source
                    .Append("        private ")
                    .Append(resultType)
                    .Append(" last")
                    .Append(export.public_name)
                    .AppendLine("Result;");
            source.AppendLine();
            source.Append("        public int Start").Append(export.public_name).Append('(');
            for (int index = 0; index < parameters.Length; ++index)
            {
                if (index != 0)
                    source.Append(", ");
                source
                    .Append(CSharpType(parameters[index].kind))
                    .Append(' ')
                    .Append(parameters[index].name);
            }
            if (parameters.Length != 0)
                source.Append(", ");
            source.AppendLine("UdonSharpBehaviour receiver, string completionEvent)");
            source.AppendLine("        {");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusDisposed;");
            source.AppendLine("            if (program == null)");
            source.AppendLine("                return StatusNotInitialized;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine(
                "            if (receiver == null || string.IsNullOrEmpty(completionEvent))"
            );
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            busy = true;");
            source.AppendLine("            pendingAsyncReceiver = receiver;");
            source.AppendLine("            pendingAsyncCompletionEvent = completionEvent;");
            source
                .Append("            pendingAsyncUdonEvent = \"")
                .Append(Escape(export.udon_event))
                .AppendLine("\";");
            source.Append("            pendingAsyncExportId = ").Append(export.id).AppendLine(";");
            source.AppendLine("            pendingAsyncGeneration = generation;");
            if (staticAsyncBackend)
            {
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.pending_object_slot))
                    .AppendLine("\", 0);");
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.completion_object_slot))
                    .AppendLine("\", 0);");
            }
            else
            {
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.resume_state_slot))
                    .AppendLine("\", 0);");
            }
            source
                .Append("            program.SetProgramVariable(\"")
                .Append(Escape(commands.command_kind_slot))
                .AppendLine("\", 0);");
            for (int index = 0; index < parameters.Length; ++index)
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(parameters[index].heap_slot))
                    .Append("\", ")
                    .Append(parameters[index].name)
                    .AppendLine(");");
            source
                .Append("            program.SendCustomEvent(\"")
                .Append(Escape(export.udon_event))
                .AppendLine("\");");
            source.AppendLine("            PumpAsyncCommand();");
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source
                .Append("        public int Get")
                .Append(export.public_name)
                .AppendLine("Status()");
            source.AppendLine("        {");
            source
                .Append("            return lastAsyncExportId == ")
                .Append(export.id)
                .AppendLine(" ? lastAsyncStatus : StatusNotInitialized;");
            source.AppendLine("        }");
            if (resultType != null)
            {
                source.AppendLine();
                source
                    .Append("        public int TryGet")
                    .Append(export.public_name)
                    .Append("Result(out ")
                    .Append(resultType)
                    .AppendLine(" result)");
                source.AppendLine("        {");
                source
                    .Append("            result = last")
                    .Append(export.public_name)
                    .AppendLine("Result;");
                source
                    .Append("            if (lastAsyncExportId != ")
                    .Append(export.id)
                    .AppendLine(")");
                source.AppendLine("                return StatusNotInitialized;");
                source.AppendLine("            return lastAsyncStatus;");
                source.AppendLine("        }");
            }
        }

        private static void EmitAsyncCommandRuntime(
            StringBuilder source,
            ExportInfo[] exports,
            AsyncCommandInfo commands,
            bool staticAsyncBackend
        )
        {
            source.AppendLine();
            source.AppendLine("        private void PumpAsyncCommand()");
            source.AppendLine("        {");
            source.AppendLine(
                "            if (!busy || program == null || pendingAsyncGeneration != generation)"
            );
            source.AppendLine("                return;");
            source
                .Append("            object rawKind = program.GetProgramVariable(\"")
                .Append(Escape(commands.command_kind_slot))
                .AppendLine("\");");
            source.AppendLine("            if (rawKind == null)");
            source.AppendLine("            {");
            source.AppendLine("                CompleteAsyncExport(StatusAbiMismatch);");
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source.AppendLine("            int kind = (int)rawKind;");
            if (staticAsyncBackend)
            {
                EmitReadProgramVariable(source, "rawPendingObject", commands.pending_object_slot);
                source.AppendLine("            if (rawPendingObject == null)");
                source.AppendLine("            {");
                source.AppendLine("                CompleteAsyncExport(StatusAbiMismatch);");
                source.AppendLine("                return;");
                source.AppendLine("            }");
                source.AppendLine("            int pendingObject = (int)rawPendingObject;");
                source.AppendLine("            if (pendingObject == 0)");
                source.AppendLine("            {");
                source.AppendLine("                if (kind != 0)");
                source.AppendLine("                    CompleteAsyncExport(StatusAbiMismatch);");
                source.AppendLine("                else");
                source.AppendLine("                    CompleteAsyncExportFromProgram();");
                source.AppendLine("                return;");
                source.AppendLine("            }");
                source.AppendLine("            pendingAsyncObject = pendingObject;");
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.pending_object_slot))
                    .AppendLine("\", 0);");
                source.AppendLine("            if (kind == 0)");
                source.AppendLine("            {");
                source.AppendLine("                pendingAsyncCompletionStatus = StatusSuccess;");
                source.AppendLine(
                    "                SendCustomEventDelayedFrames(\"_ContinueAsyncCommand\", 1);"
                );
                source.AppendLine("                return;");
                source.AppendLine("            }");
            }
            else
            {
                source
                    .Append("            object rawResume = program.GetProgramVariable(\"")
                    .Append(Escape(commands.resume_state_slot))
                    .AppendLine("\");");
                source.AppendLine("            if (rawResume == null)");
                source.AppendLine("            {");
                source.AppendLine("                CompleteAsyncExport(StatusAbiMismatch);");
                source.AppendLine("                return;");
                source.AppendLine("            }");
                source.AppendLine("            int resume = (int)rawResume;");
                source.AppendLine("            if (kind == 0)");
                source.AppendLine("            {");
                source.AppendLine("                if (resume != 0)");
                source.AppendLine("                {");
                source.AppendLine("                    FinishAsyncCommand(StatusSuccess);");
                source.AppendLine("                    return;");
                source.AppendLine("                }");
                source.AppendLine("                CompleteAsyncExportFromProgram();");
                source.AppendLine("                return;");
                source.AppendLine("            }");
            }
            EmitReadProgramVariable(source, "rawBuffer", commands.command_buffer_slot);
            EmitReadProgramVariable(source, "rawOffset", commands.command_offset_slot);
            EmitReadProgramVariable(source, "rawSize", commands.command_size_slot);
            EmitReadProgramVariable(source, "rawPointer", commands.command_pointer_slot);
            EmitReadProgramVariable(source, "rawHeap", commands.raw_heap_slot);
            source.AppendLine(
                "            if (rawBuffer == null || rawOffset == null || rawSize == null || rawPointer == null || rawHeap == null)"
            );
            source.AppendLine("            {");
            source.AppendLine("                FinishAsyncCommand(StatusAbiMismatch);");
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source.AppendLine("            int bufferId = (int)rawBuffer;");
            source.AppendLine("            int offset = (int)rawOffset;");
            source.AppendLine("            int size = (int)rawSize;");
            source.AppendLine("            int pointer = (int)rawPointer;");
            source.AppendLine("            int[] heap = (int[])rawHeap;");
            source.AppendLine("            int index = FindDeviceBuffer(bufferId);");
            source.AppendLine(
                "            if (index < 0 || deviceBuffers[index] == null || offset < 0 || size <= 0 || pointer < 0 || (offset & 3) != 0 || (size & 3) != 0 || (pointer & 3) != 0 || offset > deviceBufferLogicalBytes[index] - size || pointer > heap.Length * 4 - size)"
            );
            source.AppendLine("            {");
            source.AppendLine("                FinishAsyncCommand(StatusInvalidArgument);");
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source.AppendLine("            asyncCommandBufferIndex = index;");
            source.AppendLine("            asyncCommandOffsetWords = offset / 4;");
            source.AppendLine("            asyncCommandSizeWords = size / 4;");
            source.AppendLine("            asyncCommandPointerBytes = pointer;");
            source.AppendLine("            asyncCommandHeap = heap;");
            source.Append("            if (kind == ").Append(commands.upload_kind).AppendLine(")");
            source.AppendLine("            {");
            source.AppendLine(
                "                if (offset == 0 && size == deviceBufferLogicalBytes[index])"
            );
            source.AppendLine("                {");
            source.AppendLine(
                "                    Color32[] pixels = new Color32[deviceBuffers[index].width * deviceBuffers[index].height];"
            );
            source.AppendLine("                    CopyHeapToPixels(pixels);");
            source.AppendLine(
                "                    FinishAsyncCommand(UploadWords(index, pixels));"
            );
            source.AppendLine("                    return;");
            source.AppendLine("                }");
            source.AppendLine("                asyncCommandReadbackMode = 2;");
            source.AppendLine(
                "                VRCAsyncGPUReadback.Request(deviceBuffers[index], 0, TextureFormat.RGBA32, this);"
            );
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source
                .Append("            if (kind == ")
                .Append(commands.readback_kind)
                .AppendLine(")");
            source.AppendLine("            {");
            source.AppendLine("                asyncCommandReadbackMode = 1;");
            source.AppendLine(
                "                VRCAsyncGPUReadback.Request(deviceBuffers[index], 0, TextureFormat.RGBA32, this);"
            );
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source.AppendLine("            FinishAsyncCommand(StatusAbiMismatch);");
            source.AppendLine("        }");

            source.AppendLine();
            source.AppendLine("        private void CopyHeapToPixels(Color32[] pixels)");
            source.AppendLine("        {");
            source.AppendLine(
                "            for (int word = 0; word < asyncCommandSizeWords; ++word)"
            );
            source.AppendLine("            {");
            source.AppendLine(
                "                int heapWord = asyncCommandPointerBytes / 4 + word;"
            );
            source.AppendLine("                int value = asyncCommandHeap[heapWord];");
            source.AppendLine(
                "                pixels[asyncCommandOffsetWords + word] = new Color32((byte)value, (byte)(value >> 8), (byte)(value >> 16), (byte)(value >> 24));"
            );
            source.AppendLine("            }");
            source.AppendLine("        }");

            source.AppendLine();
            source.AppendLine(
                "        private void CompleteAsyncCommandReadback(VRCAsyncGPUReadbackRequest request)"
            );
            source.AppendLine("        {");
            source.AppendLine("            int mode = asyncCommandReadbackMode;");
            source.AppendLine("            asyncCommandReadbackMode = 0;");
            source.AppendLine(
                "            RenderTexture texture = deviceBuffers[asyncCommandBufferIndex];"
            );
            source.AppendLine(
                "            Color32[] pixels = new Color32[texture.width * texture.height];"
            );
            source.AppendLine("            if (!request.TryGetData(pixels, 0))");
            source.AppendLine("            {");
            source.AppendLine("                FinishAsyncCommand(StatusExecutionFailure);");
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source.AppendLine("            if (mode == 1)");
            source.AppendLine("            {");
            source.AppendLine(
                "                for (int word = 0; word < asyncCommandSizeWords; ++word)"
            );
            source.AppendLine("                {");
            source.AppendLine(
                "                    int heapWord = asyncCommandPointerBytes / 4 + word;"
            );
            source.AppendLine(
                "                    Color32 pixel = pixels[asyncCommandOffsetWords + word];"
            );
            source.AppendLine(
                "                    asyncCommandHeap[heapWord] = pixel.r | (pixel.g << 8) | (pixel.b << 16) | (pixel.a << 24);"
            );
            source.AppendLine("                }");
            source.AppendLine("                FinishAsyncCommand(StatusSuccess);");
            source.AppendLine("                return;");
            source.AppendLine("            }");
            source.AppendLine("            CopyHeapToPixels(pixels);");
            source.AppendLine(
                "            FinishAsyncCommand(UploadWords(asyncCommandBufferIndex, pixels));"
            );
            source.AppendLine("        }");

            source.AppendLine();
            source.AppendLine("        private void FinishAsyncCommand(int status)");
            source.AppendLine("        {");
            source
                .Append("            program.SetProgramVariable(\"")
                .Append(Escape(commands.command_kind_slot))
                .AppendLine("\", 0);");
            source.AppendLine("            asyncCommandHeap = null;");
            if (staticAsyncBackend)
                source.AppendLine("            pendingAsyncCompletionStatus = status;");
            else
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.completion_status_slot))
                    .AppendLine("\", status);");
            source.AppendLine(
                "            SendCustomEventDelayedFrames(\"_ContinueAsyncCommand\", 1);"
            );
            source.AppendLine("        }");

            source.AppendLine();
            source.AppendLine("        public void _ContinueAsyncCommand()");
            source.AppendLine("        {");
            source.AppendLine(
                "            if (!busy || program == null || pendingAsyncGeneration != generation)"
            );
            source.AppendLine("                return;");
            if (staticAsyncBackend)
            {
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.completion_object_slot))
                    .AppendLine("\", pendingAsyncObject);");
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.completion_status_slot))
                    .AppendLine("\", pendingAsyncCompletionStatus);");
                source
                    .Append("            program.SendCustomEvent(\"")
                    .Append(Escape(commands.completion_event))
                    .AppendLine("\");");
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(commands.completion_object_slot))
                    .AppendLine("\", 0);");
                source.AppendLine("            pendingAsyncObject = 0;");
                source.AppendLine("            pendingAsyncCompletionStatus = 0;");
            }
            else
                source.AppendLine("            program.SendCustomEvent(pendingAsyncUdonEvent);");
            source.AppendLine("            PumpAsyncCommand();");
            source.AppendLine("        }");

            source.AppendLine();
            source.AppendLine("        private void CompleteAsyncExportFromProgram()");
            source.AppendLine("        {");
            foreach (ExportInfo export in exports)
            {
                if (!export.async)
                    continue;
                source
                    .Append("            if (pendingAsyncExportId == ")
                    .Append(export.id)
                    .AppendLine(")");
                source.AppendLine("            {");
                source
                    .Append("                object rawStatus = program.GetProgramVariable(\"")
                    .Append(Escape(export.status_slot))
                    .AppendLine("\");");
                source.AppendLine("                if (rawStatus == null)");
                source.AppendLine("                {");
                source.AppendLine("                    CompleteAsyncExport(StatusAbiMismatch);");
                source.AppendLine("                    return;");
                source.AppendLine("                }");
                source.AppendLine("                int status = (int)rawStatus;");
                if (HasResult(export))
                {
                    source.AppendLine("                if (status == StatusSuccess)");
                    source.AppendLine("                {");
                    source
                        .Append(
                            "                    object rawResult = program.GetProgramVariable(\""
                        )
                        .Append(Escape(export.result.heap_slot))
                        .AppendLine("\");");
                    source.AppendLine("                    if (rawResult == null)");
                    source.AppendLine("                    {");
                    source.AppendLine(
                        "                        CompleteAsyncExport(StatusAbiMismatch);"
                    );
                    source.AppendLine("                        return;");
                    source.AppendLine("                    }");
                    source
                        .Append("                    last")
                        .Append(export.public_name)
                        .Append("Result = (")
                        .Append(CSharpType(export.result.kind))
                        .AppendLine(")rawResult;");
                    source.AppendLine("                }");
                }
                source.AppendLine("                CompleteAsyncExport(status);");
                source.AppendLine("                return;");
                source.AppendLine("            }");
            }
            source.AppendLine("            CompleteAsyncExport(StatusAbiMismatch);");
            source.AppendLine("        }");

            source.AppendLine();
            source.AppendLine("        private void CompleteAsyncExport(int status)");
            source.AppendLine("        {");
            source.AppendLine("            lastAsyncExportId = pendingAsyncExportId;");
            source.AppendLine("            lastAsyncStatus = status;");
            source.AppendLine("            busy = false;");
            source.AppendLine("            UdonSharpBehaviour receiver = pendingAsyncReceiver;");
            source.AppendLine("            string completionEvent = pendingAsyncCompletionEvent;");
            source.AppendLine("            pendingAsyncReceiver = null;");
            source.AppendLine("            pendingAsyncCompletionEvent = null;");
            source.AppendLine("            pendingAsyncUdonEvent = null;");
            source.AppendLine("            pendingAsyncExportId = 0;");
            source.AppendLine("            pendingAsyncGeneration = 0;");
            source.AppendLine("            if (receiver != null)");
            source.AppendLine("                receiver.SendCustomEvent(completionEvent);");
            source.AppendLine("        }");
        }

        private static void EmitReadProgramVariable(
            StringBuilder source,
            string localName,
            string slot
        )
        {
            source
                .Append("            object ")
                .Append(localName)
                .Append(" = program.GetProgramVariable(\"")
                .Append(Escape(slot))
                .AppendLine("\");");
        }

        private static void ValidateExport(ExportInfo export, HashSet<string> publicNames)
        {
            if (export == null || export.id <= 0)
                throw new ArgumentException(
                    "Only positive scalar or one-dimensional array exports are supported."
                );
            RequireIdentifier(export.public_name, "export.public_name", allowDots: false);
            if (!publicNames.Add(export.public_name))
                throw new ArgumentException("Duplicate public export name.");
            RequireSymbol(export.udon_event, "export.udon_event");
            RequireSymbol(export.status_slot, "export.status_slot");
            ExportParameterInfo[] parameters =
                export.parameters ?? Array.Empty<ExportParameterInfo>();
            for (int index = 0; index < parameters.Length; ++index)
            {
                ExportParameterInfo parameter = parameters[index];
                if (parameter == null || parameter.index != index)
                    throw new ArgumentException(
                        "Export parameters must be contiguous and ordered."
                    );
                RequireIdentifier(parameter.name, "parameter.name", allowDots: false);
                RequireSymbol(parameter.heap_slot, "parameter.heap_slot");
                CSharpType(parameter.kind);
            }
            if (HasResult(export))
            {
                RequireSymbol(export.result.heap_slot, "result.heap_slot");
                CSharpType(export.result.kind);
            }
        }

        private static void ValidateAsyncCommands(AsyncCommandInfo commands)
        {
            if (
                commands == null
                || commands.upload_kind <= 0
                || commands.readback_kind <= 0
                || commands.upload_kind == commands.readback_kind
            )
                throw new ArgumentException("Async command ABI is missing or invalid.");
            RequireSymbol(commands.resume_state_slot, "async.resume_state_slot");
            RequireSymbol(commands.completion_status_slot, "async.completion_status_slot");
            if (
                !string.IsNullOrEmpty(commands.completion_object_slot)
                || !string.IsNullOrEmpty(commands.pending_object_slot)
                || !string.IsNullOrEmpty(commands.completion_event)
            )
            {
                RequireSymbol(commands.pending_object_slot, "async.pending_object_slot");
                RequireSymbol(commands.completion_object_slot, "async.completion_object_slot");
                RequireSymbol(commands.completion_event, "async.completion_event");
            }
            RequireSymbol(commands.command_kind_slot, "async.command_kind_slot");
            RequireSymbol(commands.command_buffer_slot, "async.command_buffer_slot");
            RequireSymbol(commands.command_offset_slot, "async.command_offset_slot");
            RequireSymbol(commands.command_size_slot, "async.command_size_slot");
            RequireSymbol(commands.command_pointer_slot, "async.command_pointer_slot");
            RequireSymbol(commands.raw_heap_slot, "async.raw_heap_slot");
        }

        private static bool HasResult(ExportInfo export)
        {
            return export.result != null
                && (
                    !string.IsNullOrEmpty(export.result.kind)
                    || !string.IsNullOrEmpty(export.result.heap_slot)
                );
        }

        private static string CSharpType(string kind)
        {
            switch (kind)
            {
                case "i32":
                    return "int";
                case "f32":
                    return "float";
                case "i32_array":
                    return "int[]";
                case "f32_array":
                    return "float[]";
                case "string":
                    return "string";
                default:
                    throw new ArgumentException("Unsupported generated wrapper type: " + kind);
            }
        }

        private static void RequireIdentifier(string value, string name, bool allowDots)
        {
            if (string.IsNullOrEmpty(value))
                throw new ArgumentException("Identifier is empty.", name);
            string[] parts = allowDots ? value.Split('.') : new[] { value };
            foreach (string part in parts)
            {
                if (part.Length == 0 || (!char.IsLetter(part[0]) && part[0] != '_'))
                    throw new ArgumentException("Invalid identifier.", name);
                for (int index = 1; index < part.Length; ++index)
                    if (!char.IsLetterOrDigit(part[index]) && part[index] != '_')
                        throw new ArgumentException("Invalid identifier.", name);
            }
        }

        private static void RequireSymbol(string value, string name)
        {
            RequireIdentifier(value, name, allowDots: false);
        }

        private static string Escape(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
