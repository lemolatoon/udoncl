using System;
using System.Collections.Generic;
using System.Text;
using UnityEngine;

namespace Lemolatoon.Udoncl.Editor
{
    public static class VRCWrapperGenerator
    {
        public static string GenerateFromJson(
            string manifestJson,
            string namespaceName,
            string className
        )
        {
            if (string.IsNullOrWhiteSpace(manifestJson))
                throw new ArgumentException("Manifest JSON is empty.", nameof(manifestJson));
            UdonclManifest manifest = JsonUtility.FromJson<UdonclManifest>(manifestJson);
            return Generate(manifest, namespaceName, className);
        }

        internal static string Generate(
            UdonclManifest manifest,
            string namespaceName,
            string className
        )
        {
            if (manifest == null)
                throw new ArgumentNullException(nameof(manifest));
            RequireIdentifier(namespaceName, nameof(namespaceName), allowDots: true);
            RequireIdentifier(className, nameof(className), allowDots: false);
            if (manifest.physical_export_abi != "udonsharp-worlds-sdk-3.10.5")
                throw new ArgumentException("Unsupported physical export ABI.", nameof(manifest));

            ExportInfo[] exports =
                manifest.exports == null
                    ? Array.Empty<ExportInfo>()
                    : (ExportInfo[])manifest.exports.Clone();
            Array.Sort(exports, (left, right) => left.id.CompareTo(right.id));
            HashSet<string> publicNames = new HashSet<string>(StringComparer.Ordinal);
            StringBuilder source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using Lemolatoon.Udoncl;");
            source.AppendLine("using UdonSharp;");
            source.AppendLine("using UnityEngine;");
            source.AppendLine("using VRC.Udon;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine();
            source.AppendLine("{");
            source
                .Append("    public sealed class ")
                .Append(className)
                .AppendLine(" : UdonSharpBehaviour");
            source.AppendLine("    {");
            source.AppendLine("        [SerializeField] private UdonBehaviour program;");
            source.AppendLine();
            source.AppendLine("        public void BindProgram(UdonBehaviour value)");
            source.AppendLine("        {");
            source.AppendLine("            program = value;");
            source.AppendLine("        }");

            foreach (ExportInfo export in exports)
            {
                ValidateExport(export, publicNames);
                EmitExport(source, export);
            }

            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        private static void EmitExport(StringBuilder source, ExportInfo export)
        {
            ExportParameterInfo[] parameters =
                export.parameters ?? Array.Empty<ExportParameterInfo>();
            string resultType = export.result == null ? null : CSharpType(export.result.kind);
            source.AppendLine();
            source.Append("        public UdonClStatus Try").Append(export.public_name).Append('(');
            for (int index = 0; index < parameters.Length; ++index)
            {
                if (index != 0)
                    source.Append(", ");
                source
                    .Append(CSharpType(parameters[index].kind))
                    .Append(' ')
                    .Append(parameters[index].name);
            }
            if (resultType != null)
            {
                if (parameters.Length != 0)
                    source.Append(", ");
                source.Append("out ").Append(resultType).Append(" result");
            }
            source.AppendLine(")");
            source.AppendLine("        {");
            if (resultType != null)
                source.AppendLine("            result = default;");
            source.AppendLine("            if (program == null)");
            source.AppendLine("                return UdonClStatus.NotInitialized;");
            for (int index = 0; index < parameters.Length; ++index)
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(parameters[index].heap_slot))
                    .Append("\", ")
                    .Append(parameters[index].name)
                    .AppendLine(");");
            source
                .Append("            program.SendCustomEvent(\"")
                .Append(Escape(export.udon_event))
                .AppendLine("\");");
            source
                .Append("            object rawStatus = program.GetProgramVariable(\"")
                .Append(Escape(export.status_slot))
                .AppendLine("\");");
            source.AppendLine("            if (!(rawStatus is int))");
            source.AppendLine("                return UdonClStatus.AbiMismatch;");
            source.AppendLine("            UdonClStatus status = (UdonClStatus)(int)rawStatus;");
            source.AppendLine("            if (status != UdonClStatus.Success)");
            source.AppendLine("                return status;");
            if (resultType != null)
            {
                source
                    .Append("            object rawResult = program.GetProgramVariable(\"")
                    .Append(Escape(export.result.heap_slot))
                    .AppendLine("\");");
                source
                    .Append("            if (!(rawResult is ")
                    .Append(resultType)
                    .AppendLine("))");
                source.AppendLine("                return UdonClStatus.AbiMismatch;");
                source
                    .Append("            result = (")
                    .Append(resultType)
                    .AppendLine(")rawResult;");
            }
            source.AppendLine("            return UdonClStatus.Success;");
            source.AppendLine("        }");
        }

        private static void ValidateExport(ExportInfo export, HashSet<string> publicNames)
        {
            if (export == null || export.id <= 0 || export.async)
                throw new ArgumentException(
                    "Only positive synchronous scalar exports are supported."
                );
            RequireIdentifier(export.public_name, "export.public_name", allowDots: false);
            if (!publicNames.Add(export.public_name))
                throw new ArgumentException("Duplicate public export name.");
            RequireSymbol(export.udon_event, "export.udon_event");
            RequireSymbol(export.status_slot, "export.status_slot");
            ExportParameterInfo[] parameters =
                export.parameters ?? Array.Empty<ExportParameterInfo>();
            for (int index = 0; index < parameters.Length; ++index)
            {
                ExportParameterInfo parameter = parameters[index];
                if (parameter == null || parameter.index != index)
                    throw new ArgumentException(
                        "Export parameters must be contiguous and ordered."
                    );
                RequireIdentifier(parameter.name, "parameter.name", allowDots: false);
                RequireSymbol(parameter.heap_slot, "parameter.heap_slot");
                CSharpType(parameter.kind);
            }
            if (export.result != null)
            {
                RequireSymbol(export.result.heap_slot, "result.heap_slot");
                CSharpType(export.result.kind);
            }
        }

        private static string CSharpType(string kind)
        {
            switch (kind)
            {
                case "i32":
                    return "int";
                case "f32":
                    return "float";
                default:
                    throw new ArgumentException("Unsupported generated wrapper type: " + kind);
            }
        }

        private static void RequireIdentifier(string value, string name, bool allowDots)
        {
            if (string.IsNullOrEmpty(value))
                throw new ArgumentException("Identifier is empty.", name);
            string[] parts = allowDots ? value.Split('.') : new[] { value };
            foreach (string part in parts)
            {
                if (part.Length == 0 || (!char.IsLetter(part[0]) && part[0] != '_'))
                    throw new ArgumentException("Invalid identifier.", name);
                for (int index = 1; index < part.Length; ++index)
                    if (!char.IsLetterOrDigit(part[index]) && part[index] != '_')
                        throw new ArgumentException("Invalid identifier.", name);
            }
        }

        private static void RequireSymbol(string value, string name)
        {
            RequireIdentifier(value, name, allowDots: false);
        }

        private static string Escape(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
}
