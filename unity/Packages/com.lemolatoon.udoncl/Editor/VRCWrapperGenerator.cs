    public static class VRCWrapperGenerator
    {
        public static string GenerateFromJson(
            string manifestJson,
            string namespaceName,
            string className
        )
        {
            if (string.IsNullOrWhiteSpace(manifestJson))
                throw new ArgumentException("Manifest JSON is empty.", nameof(manifestJson));
            UdonclManifest manifest = JsonUtility.FromJson<UdonclManifest>(manifestJson);
            return Generate(manifest, namespaceName, className);
        }

        public static string GenerateOnnxFromJson(
            string manifestJson,
            string namespaceName,
            string className
        )
        {
            if (string.IsNullOrWhiteSpace(manifestJson))
                throw new ArgumentException("Manifest JSON is empty.", nameof(manifestJson));
            UdonclManifest manifest = JsonUtility.FromJson<UdonclManifest>(manifestJson);
            return GenerateOnnx(manifest, namespaceName, className);
        }

        internal static string GenerateOnnx(
            UdonclManifest manifest,
            string namespaceName,
            string className
        )
        {
            if (manifest == null)
                throw new ArgumentNullException(nameof(manifest));
            RequireIdentifier(namespaceName, nameof(namespaceName), allowDots: true);
            RequireIdentifier(className, nameof(className), allowDots: false);
            if (
                manifest.artifact_stage != "unity-udon-onnx-model"
                || manifest.runtime_abi_version != 1
                || manifest.model_inputs == null
                || manifest.model_inputs.Length == 0
                || manifest.model_outputs == null
                || manifest.model_outputs.Length == 0
            )
                throw new ArgumentException("Unsupported ONNX binding ABI.", nameof(manifest));

            StringBuilder source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using UdonSharp;");
            source.AppendLine("using UnityEngine;");
            source.AppendLine("using VRC.SDK3.Rendering;");
            source.AppendLine("using VRC.SDKBase;");
            source.AppendLine("using VRC.Udon;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine();
            source.AppendLine("{");
            source
                .Append("    public sealed class ")
                .Append(className)
                .AppendLine(" : UdonSharpBehaviour");
            source.AppendLine("    {");
            source.AppendLine("        public const int StatusSuccess = 0;");
            source.AppendLine("        public const int StatusNotInitialized = -1;");
            source.AppendLine("        public const int StatusBusy = -2;");
            source.AppendLine("        public const int StatusInvalidArgument = -3;");
            source.AppendLine("        public const int StatusAbiMismatch = -4;");
            source.AppendLine("        public const int StatusExecutionFailure = -5;");
            source.AppendLine("        public const int StatusDisposed = -6;");
            source.AppendLine();
            source.AppendLine("        [SerializeField] private UdonBehaviour program;");
            source.AppendLine("        [SerializeField] private int[] deviceBufferIds;");
            source.AppendLine("        [SerializeField] private int[] deviceBufferLogicalBytes;");
            source.AppendLine("        [SerializeField] private RenderTexture[] deviceBuffers;");
            source.AppendLine("        [SerializeField] private Material bufferCopyMaterial;");
            source.AppendLine("        private Texture2D[] uploadTextures;");
            source.AppendLine("        private int pendingReadbackIndex;");
            source.AppendLine("        private float[] pendingFloatReadback;");
            source.AppendLine("        private int[] pendingIntReadback;");
            source.AppendLine("        private UdonSharpBehaviour pendingReadbackReceiver;");
            source.AppendLine("        private string pendingReadbackEvent;");
            source.AppendLine("        private int lastReadbackStatus;");
            source.AppendLine("        private bool busy;");
            source.AppendLine("        private bool readbackBusy;");
            source.AppendLine("        private bool disposed;");
            source.AppendLine();
            source.AppendLine("        public bool IsInitialized()");
            source.AppendLine("        {");
            source.AppendLine("            return program != null && !disposed;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public int TryDispose()");
            source.AppendLine("        {");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusSuccess;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            disposed = true;");
            source.AppendLine("            program = null;");
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public int TryRun()");
            source.AppendLine("        {");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusDisposed;");
            source.AppendLine("            if (program == null)");
            source.AppendLine("                return StatusNotInitialized;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            busy = true;");
            source.AppendLine("            program.SendCustomEvent(\"_run\");");
            source.AppendLine("            busy = false;");
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");

            EmitBufferTransfers(source, "private");
            HashSet<string> generatedMethods = new HashSet<string>(StringComparer.Ordinal);
            for (int index = 0; index < manifest.model_inputs.Length; ++index)
            {
                UdonOnnxIoInfo input = manifest.model_inputs[index];
                ValidateOnnxIo(input, index);
                string method = "TryWriteInput" + PublicIoName(input.name, index);
                if (!generatedMethods.Add(method))
                    throw new ArgumentException("ONNX input names collide in the U# API.");
                source.AppendLine();
                source
                    .Append("        public int ")
                    .Append(method)
                    .Append('(')
                    .Append(input.data_type == "float32" ? "float[]" : "int[]")
                    .AppendLine(" source)");
                source.AppendLine("        {");
                source
                    .Append("            return ")
                    .Append(
                        input.data_type == "float32" ? "TryWriteFloatBuffer(" : "TryWriteIntBuffer("
                    )
                    .Append(index + 1)
                    .AppendLine(", source);");
                source.AppendLine("        }");
            }
            for (int index = 0; index < manifest.model_outputs.Length; ++index)
            {
                UdonOnnxIoInfo output = manifest.model_outputs[index];
                ValidateOnnxIo(output, index);
                string method = "StartReadOutput" + PublicIoName(output.name, index);
                if (!generatedMethods.Add(method))
                    throw new ArgumentException("ONNX output names collide in the U# API.");
                source.AppendLine();
                source
                    .Append("        public int ")
                    .Append(method)
                    .Append('(')
                    .Append(output.data_type == "float32" ? "float[]" : "int[]")
                    .AppendLine(
                        " destination, UdonSharpBehaviour receiver, string completionEvent)"
                    );
                source.AppendLine("        {");
                source
                    .Append("            return ")
                    .Append(
                        output.data_type == "float32"
                            ? "StartReadFloatBuffer("
                            : "StartReadIntBuffer("
                    )
                    .Append(0x40000001 + index)
                    .AppendLine(", destination, receiver, completionEvent);");
                source.AppendLine("        }");
            }
            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        internal static string Generate(
            UdonclManifest manifest,
            string namespaceName,
            string className
        )
        {
            if (manifest == null)
                throw new ArgumentNullException(nameof(manifest));
            RequireIdentifier(namespaceName, nameof(namespaceName), allowDots: true);
            RequireIdentifier(className, nameof(className), allowDots: false);
            if (manifest.physical_export_abi != "udonsharp-worlds-sdk-3.10.5")
                throw new ArgumentException("Unsupported physical export ABI.", nameof(manifest));

            ExportInfo[] exports =
                manifest.exports == null
                    ? Array.Empty<ExportInfo>()
                    : (ExportInfo[])manifest.exports.Clone();
            if (exports.Length == 0)
                throw new ArgumentException("Typed wrapper requires at least one export.");
            Array.Sort(exports, (left, right) => left.id.CompareTo(right.id));
            HashSet<string> publicNames = new HashSet<string>(StringComparer.Ordinal);
            StringBuilder source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using UdonSharp;");
            source.AppendLine("using UnityEngine;");
            source.AppendLine("using VRC.SDK3.Rendering;");
            source.AppendLine("using VRC.SDKBase;");
            source.AppendLine("using VRC.Udon;");
            source.AppendLine();
            source.Append("namespace ").Append(namespaceName).AppendLine();
            source.AppendLine("{");
            source
                .Append("    public sealed class ")
                .Append(className)
                .AppendLine(" : UdonSharpBehaviour");
            source.AppendLine("    {");
            source.AppendLine("        public const int StatusSuccess = 0;");
            source.AppendLine("        public const int StatusNotInitialized = -1;");
            source.AppendLine("        public const int StatusBusy = -2;");
            source.AppendLine("        public const int StatusInvalidArgument = -3;");
            source.AppendLine("        public const int StatusAbiMismatch = -4;");
            source.AppendLine("        public const int StatusExecutionFailure = -5;");
            source.AppendLine("        public const int StatusDisposed = -6;");
            source.AppendLine();
            source.AppendLine("        [SerializeField] private UdonBehaviour program;");
            DeviceBufferInfo[] buffers =
                manifest.device == null || manifest.device.buffers == null
                    ? Array.Empty<DeviceBufferInfo>()
                    : manifest.device.buffers;
            if (buffers.Length != 0)
            {
                ValidateDeviceBuffers(buffers);
                source.AppendLine("        [SerializeField] private int[] deviceBufferIds;");
                source.AppendLine(
                    "        [SerializeField] private int[] deviceBufferLogicalBytes;"
                );
                source.AppendLine(
                    "        [SerializeField] private RenderTexture[] deviceBuffers;"
                );
                source.AppendLine("        [SerializeField] private Material bufferCopyMaterial;");
                source.AppendLine("        private Texture2D[] uploadTextures;");
                source.AppendLine("        private int pendingReadbackIndex;");
                source.AppendLine("        private float[] pendingFloatReadback;");
                source.AppendLine("        private int[] pendingIntReadback;");
                source.AppendLine("        private UdonSharpBehaviour pendingReadbackReceiver;");
                source.AppendLine("        private string pendingReadbackEvent;");
                source.AppendLine("        private int lastReadbackStatus;");
            }
            source.AppendLine("        private bool busy;");
            source.AppendLine("        private bool readbackBusy;");
            source.AppendLine("        private bool disposed;");
            source.AppendLine();
            source.AppendLine("        public int TryBindProgram(UdonBehaviour value)");
            source.AppendLine("        {");
            source.AppendLine("            if (value == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            program = value;");
            source.AppendLine("            busy = false;");
            source.AppendLine("            disposed = false;");
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public bool IsInitialized()");
            source.AppendLine("        {");
            source.AppendLine("            return program != null && !disposed;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public int TryDispose()");
            source.AppendLine("        {");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusSuccess;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            disposed = true;");
            source.AppendLine("            program = null;");
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");

            if (buffers.Length != 0)
                EmitBufferTransfers(source, "public");

            foreach (ExportInfo export in exports)
            {
                ValidateExport(export, publicNames);
                EmitExport(source, export);
            }

            source.AppendLine("    }");
            source.AppendLine("}");
            return source.ToString();
        }

        private static void EmitBufferTransfers(StringBuilder source, string visibility)
        {
            source.AppendLine();
            source.AppendLine("        private int FindDeviceBuffer(int bufferId)");
            source.AppendLine("        {");
            source.AppendLine(
                "            if (deviceBufferIds == null || deviceBuffers == null || deviceBufferLogicalBytes == null)"
            );
            source.AppendLine("                return -1;");
            source.AppendLine(
                "            for (int index = 0; index < deviceBufferIds.Length; ++index)"
            );
            source.AppendLine("                if (deviceBufferIds[index] == bufferId)");
            source.AppendLine("                    return index;");
            source.AppendLine("            return -1;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private int ValidateTransfer(int bufferId, int words)");
            source.AppendLine("        {");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusDisposed;");
            source.AppendLine("            if (busy || readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            if (program == null || bufferCopyMaterial == null)");
            source.AppendLine("                return StatusNotInitialized;");
            source.AppendLine("            int index = FindDeviceBuffer(bufferId);");
            source.AppendLine(
                "            if (index < 0 || deviceBuffers[index] == null || words < 0 || words * 4 != deviceBufferLogicalBytes[index])"
            );
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            return index;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private Color32 PackWord(int word)");
            source.AppendLine("        {");
            source.AppendLine(
                "            return new Color32((byte)word, (byte)(word >> 8), (byte)(word >> 16), (byte)(word >> 24));"
            );
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private int UnpackWord(Color32 pixel)");
            source.AppendLine("        {");
            source.AppendLine(
                "            return pixel.r | (pixel.g << 8) | (pixel.b << 16) | (pixel.a << 24);"
            );
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        private int UploadWords(int index, Color32[] pixels)");
            source.AppendLine("        {");
            source.AppendLine("            if (uploadTextures == null)");
            source.AppendLine(
                "                uploadTextures = new Texture2D[deviceBuffers.Length];"
            );
            source.AppendLine("            RenderTexture destination = deviceBuffers[index];");
            source.AppendLine("            Texture2D staging = uploadTextures[index];");
            source.AppendLine("            if (staging == null)");
            source.AppendLine("            {");
            source.AppendLine(
                "                staging = new Texture2D(destination.width, destination.height, TextureFormat.RGBA32, false, true);"
            );
            source.AppendLine("                uploadTextures[index] = staging;");
            source.AppendLine("            }");
            source.AppendLine("            staging.SetPixels32(pixels);");
            source.AppendLine("            staging.Apply(false, false);");
            source.AppendLine(
                "            VRCGraphics.Blit(staging, destination, bufferCopyMaterial);"
            );
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        " + visibility + " int TryWriteFloatBuffer(int bufferId, float[] source)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (source == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            int index = ValidateTransfer(bufferId, source.Length);");
            source.AppendLine("            if (index < 0)");
            source.AppendLine("                return index;");
            source.AppendLine(
                "            Color32[] pixels = new Color32[deviceBuffers[index].width * deviceBuffers[index].height];"
            );
            source.AppendLine("            for (int word = 0; word < source.Length; ++word)");
            source.AppendLine(
                "                pixels[word] = PackWord(System.BitConverter.SingleToInt32Bits(source[word]));"
            );
            source.AppendLine("            return UploadWords(index, pixels);");
            source.AppendLine("        }");
            source.AppendLine();
            source
                .Append("        ")
                .Append(visibility)
                .AppendLine(" int TryWriteIntBuffer(int bufferId, int[] source)");
            source.AppendLine("        {");
            source.AppendLine("            if (source == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            int index = ValidateTransfer(bufferId, source.Length);");
            source.AppendLine("            if (index < 0)");
            source.AppendLine("                return index;");
            source.AppendLine(
                "            Color32[] pixels = new Color32[deviceBuffers[index].width * deviceBuffers[index].height];"
            );
            source.AppendLine("            for (int word = 0; word < source.Length; ++word)");
            source.AppendLine("                pixels[word] = PackWord(source[word]);");
            source.AppendLine("            return UploadWords(index, pixels);");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        private int StartReadback(int bufferId, int words, UdonSharpBehaviour receiver, string completionEvent)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine(
                "            if (receiver == null || string.IsNullOrEmpty(completionEvent))"
            );
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            int index = ValidateTransfer(bufferId, words);");
            source.AppendLine("            if (index < 0)");
            source.AppendLine("                return index;");
            source.AppendLine("            readbackBusy = true;");
            source.AppendLine("            pendingReadbackIndex = index;");
            source.AppendLine("            pendingReadbackReceiver = receiver;");
            source.AppendLine("            pendingReadbackEvent = completionEvent;");
            source.AppendLine("            lastReadbackStatus = StatusBusy;");
            source.AppendLine(
                "            VRCAsyncGPUReadback.Request(deviceBuffers[index], 0, TextureFormat.RGBA32, this);"
            );
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        "
                    + visibility
                    + " int StartReadFloatBuffer(int bufferId, float[] destination, UdonSharpBehaviour receiver, string completionEvent)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (destination == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            if (readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            pendingFloatReadback = destination;");
            source.AppendLine("            pendingIntReadback = null;");
            source.AppendLine(
                "            int status = StartReadback(bufferId, destination.Length, receiver, completionEvent);"
            );
            source.AppendLine("            if (status != StatusSuccess)");
            source.AppendLine("                pendingFloatReadback = null;");
            source.AppendLine("            return status;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        "
                    + visibility
                    + " int StartReadIntBuffer(int bufferId, int[] destination, UdonSharpBehaviour receiver, string completionEvent)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (destination == null)");
            source.AppendLine("                return StatusInvalidArgument;");
            source.AppendLine("            if (readbackBusy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            pendingIntReadback = destination;");
            source.AppendLine("            pendingFloatReadback = null;");
            source.AppendLine(
                "            int status = StartReadback(bufferId, destination.Length, receiver, completionEvent);"
            );
            source.AppendLine("            if (status != StatusSuccess)");
            source.AppendLine("                pendingIntReadback = null;");
            source.AppendLine("            return status;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine("        public int GetLastReadbackStatus()");
            source.AppendLine("        {");
            source.AppendLine("            return lastReadbackStatus;");
            source.AppendLine("        }");
            source.AppendLine();
            source.AppendLine(
                "        public override void OnAsyncGpuReadbackComplete(VRCAsyncGPUReadbackRequest request)"
            );
            source.AppendLine("        {");
            source.AppendLine("            if (!readbackBusy)");
            source.AppendLine("                return;");
            source.AppendLine(
                "            RenderTexture source = deviceBuffers[pendingReadbackIndex];"
            );
            source.AppendLine(
                "            Color32[] pixels = new Color32[source.width * source.height];"
            );
            source.AppendLine("            bool success = request.TryGetData(pixels, 0);");
            source.AppendLine("            if (success)");
            source.AppendLine("            {");
            source.AppendLine(
                "                int words = pendingFloatReadback != null ? pendingFloatReadback.Length : pendingIntReadback.Length;"
            );
            source.AppendLine("                for (int word = 0; word < words; ++word)");
            source.AppendLine("                {");
            source.AppendLine("                    int bits = UnpackWord(pixels[word]);");
            source.AppendLine("                    if (pendingFloatReadback != null)");
            source.AppendLine(
                "                        pendingFloatReadback[word] = System.BitConverter.Int32BitsToSingle(bits);"
            );
            source.AppendLine("                    else");
            source.AppendLine("                        pendingIntReadback[word] = bits;");
            source.AppendLine("                }");
            source.AppendLine("            }");
            source.AppendLine(
                "            lastReadbackStatus = success ? StatusSuccess : StatusExecutionFailure;"
            );
            source.AppendLine("            readbackBusy = false;");
            source.AppendLine("            pendingFloatReadback = null;");
            source.AppendLine("            pendingIntReadback = null;");
            source.AppendLine("            UdonSharpBehaviour receiver = pendingReadbackReceiver;");
            source.AppendLine("            string completionEvent = pendingReadbackEvent;");
            source.AppendLine("            pendingReadbackReceiver = null;");
            source.AppendLine("            pendingReadbackEvent = null;");
            source.AppendLine("            if (receiver != null)");
            source.AppendLine("                receiver.SendCustomEvent(completionEvent);");
            source.AppendLine("        }");
        }

        private static void ValidateDeviceBuffers(DeviceBufferInfo[] buffers)
        {
            HashSet<int> ids = new HashSet<int>();
            foreach (DeviceBufferInfo buffer in buffers)
                if (
                    buffer == null
                    || buffer.id < 0
                    || !ids.Add(buffer.id)
                    || buffer.logical_bytes <= 0
                    || buffer.logical_bytes % 4 != 0
                    || buffer.width <= 0
                    || buffer.height <= 0
                    || buffer.width * buffer.height * 4 < buffer.logical_bytes
                    || buffer.format != "rgba8_unorm"
                )
                    throw new ArgumentException(
                        "Unsupported generated Device buffer transfer ABI."
                    );
        }

        private static void ValidateOnnxIo(UdonOnnxIoInfo entry, int index)
        {
            if (
                entry == null
                || entry.index != index
                || string.IsNullOrWhiteSpace(entry.name)
                || (entry.data_type != "float32" && entry.data_type != "int32")
                || entry.words <= 0
                || entry.slot < 0
            )
                throw new ArgumentException("Unsupported ONNX model I/O binding.");
        }

        private static string PublicIoName(string name, int index)
        {
            StringBuilder result = new StringBuilder();
            bool capitalize = true;
            foreach (char character in name)
            {
                if (!char.IsLetterOrDigit(character))
                {
                    capitalize = true;
                    continue;
                }
                if (result.Length == 0 && char.IsDigit(character))
                    result.Append("Value");
                result.Append(capitalize ? char.ToUpperInvariant(character) : character);
                capitalize = false;
            }
            if (result.Length == 0)
                result.Append("Value").Append(index);
            return result.ToString();
        }

        public static string BindingClassName(string programName)
        {
            if (string.IsNullOrEmpty(programName))
                throw new ArgumentException("Program name is empty.", nameof(programName));
            StringBuilder result = new StringBuilder("Udoncl");
            bool capitalize = true;
            foreach (char character in programName)
            {
                if (!char.IsLetterOrDigit(character))
                {
                    capitalize = true;
                    continue;
                }
                result.Append(capitalize ? char.ToUpperInvariant(character) : character);
                capitalize = false;
            }
            return result + "Binding";
        }

        private static void EmitExport(StringBuilder source, ExportInfo export)
        {
            ExportParameterInfo[] parameters =
                export.parameters ?? Array.Empty<ExportParameterInfo>();
            string resultType = HasResult(export) ? CSharpType(export.result.kind) : null;
            source.AppendLine();
            source.Append("        public int Try").Append(export.public_name).Append('(');
            for (int index = 0; index < parameters.Length; ++index)
            {
                if (index != 0)
                    source.Append(", ");
                source
                    .Append(CSharpType(parameters[index].kind))
                    .Append(' ')
                    .Append(parameters[index].name);
            }
            if (resultType != null)
            {
                if (parameters.Length != 0)
                    source.Append(", ");
                source.Append("out ").Append(resultType).Append(" result");
            }
            source.AppendLine(")");
            source.AppendLine("        {");
            if (resultType != null)
                source.AppendLine("            result = default;");
            source.AppendLine("            if (disposed)");
            source.AppendLine("                return StatusDisposed;");
            source.AppendLine("            if (program == null)");
            source.AppendLine("                return StatusNotInitialized;");
            source.AppendLine("            if (busy)");
            source.AppendLine("                return StatusBusy;");
            source.AppendLine("            busy = true;");
            for (int index = 0; index < parameters.Length; ++index)
                source
                    .Append("            program.SetProgramVariable(\"")
                    .Append(Escape(parameters[index].heap_slot))
                    .Append("\", ")
                    .Append(parameters[index].name)
                    .AppendLine(");");
            source
                .Append("            program.SendCustomEvent(\"")
                .Append(Escape(export.udon_event))
                .AppendLine("\");");
            source
                .Append("            object rawStatus = program.GetProgramVariable(\"")
                .Append(Escape(export.status_slot))
                .AppendLine("\");");
            source.AppendLine("            if (rawStatus == null)");
            source.AppendLine("            {");
            source.AppendLine("                busy = false;");
            source.AppendLine("                return StatusAbiMismatch;");
            source.AppendLine("            }");
            source.AppendLine("            int status = (int)rawStatus;");
            source.AppendLine("            busy = false;");
            source.AppendLine("            if (status != StatusSuccess)");
            source.AppendLine("                return status;");
            if (resultType != null)
            {
                source
                    .Append("            object rawResult = program.GetProgramVariable(\"")
                    .Append(Escape(export.result.heap_slot))
                    .AppendLine("\");");
                source.AppendLine("            if (rawResult == null)");
                source.AppendLine("                return StatusAbiMismatch;");
                source
                    .Append("            result = (")
                    .Append(resultType)
                    .AppendLine(")rawResult;");
            }
            source.AppendLine("            return StatusSuccess;");
            source.AppendLine("        }");
        }

        private static void ValidateExport(ExportInfo export, HashSet<string> publicNames)
        {
            if (export == null || export.id <= 0 || export.async)
                throw new ArgumentException(
                    "Only positive synchronous scalar or one-dimensional array exports are supported."
                );
            RequireIdentifier(export.public_name, "export.public_name", allowDots: false);
            if (!publicNames.Add(export.public_name))
                throw new ArgumentException("Duplicate public export name.");
            RequireSymbol(export.udon_event, "export.udon_event");
            RequireSymbol(export.status_slot, "export.status_slot");
            ExportParameterInfo[] parameters =
                export.parameters ?? Array.Empty<ExportParameterInfo>();
            for (int index = 0; index < parameters.Length; ++index)
            {
                ExportParameterInfo parameter = parameters[index];
                if (parameter == null || parameter.index != index)
                    throw new ArgumentException(
                        "Export parameters must be contiguous and ordered."
                    );
                RequireIdentifier(parameter.name, "parameter.name", allowDots: false);
                RequireSymbol(parameter.heap_slot, "parameter.heap_slot");
                CSharpType(parameter.kind);
            }
            if (HasResult(export))
            {
                RequireSymbol(export.result.heap_slot, "result.heap_slot");
                CSharpType(export.result.kind);
            }
        }

        private static bool HasResult(ExportInfo export)
        {
            return export.result != null
                && (
                    !string.IsNullOrEmpty(export.result.kind)
                    || !string.IsNullOrEmpty(export.result.heap_slot)
                );
        }

        private static string CSharpType(string kind)
        {
            switch (kind)
            {
                case "i32":
                    return "int";
                case "f32":
                    return "float";
                case "i32_array":
                    return "int[]";
                case "f32_array":
                    return "float[]";
                default:
                    throw new ArgumentException("Unsupported generated wrapper type: " + kind);
            }
        }

        private static void RequireIdentifier(string value, string name, bool allowDots)
        {
            if (string.IsNullOrEmpty(value))
                throw new ArgumentException("Identifier is empty.", name);
            string[] parts = allowDots ? value.Split('.') : new[] { value };
            foreach (string part in parts)
            {
                if (part.Length == 0 || (!char.IsLetter(part[0]) && part[0] != '_'))
                    throw new ArgumentException("Invalid identifier.", name);
                for (int index = 1; index < part.Length; ++index)
                    if (!char.IsLetterOrDigit(part[index]) && part[index] != '_')
                        throw new ArgumentException("Invalid identifier.", name);
            }
        }

        private static void RequireSymbol(string value, string name)
        {
            RequireIdentifier(value, name, allowDots: false);
        }

        private static string Escape(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
