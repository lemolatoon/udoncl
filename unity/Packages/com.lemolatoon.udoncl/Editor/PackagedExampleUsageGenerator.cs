using System;

namespace Lemolatoon.Udoncl.Editor
{
    internal sealed class PackagedExampleUsage
    {
        public PackagedExampleUsage(string className, string source)
        {
            ClassName = className;
            Source = source;
        }

        public string ClassName { get; }
        public string Source { get; }
    }

    internal static class PackagedExampleUsageGenerator
    {
        internal static PackagedExampleUsage ForProgram(string programName)
        {
            switch (programName)
            {
                case "hello_dispatch":
                    return new PackagedExampleUsage(
                        "UdonclHelloDispatchExample",
                        HelloDispatchSource
                    );
                case "saxpy_demo":
                    return new PackagedExampleUsage("UdonclSaxpyDemoExample", SaxpySource);
                default:
                    return null;
            }
        }

        private const string HelloDispatchSource =
            @"// <auto-generated />
using UdonSharp;
using UnityEngine;
using VRC.SDKBase;

namespace Lemolatoon.Udoncl.Generated
{
    [UdonBehaviourSyncMode(BehaviourSyncMode.None)]
    public sealed class UdonclHelloDispatchExample : UdonSharpBehaviour
    {
        [SerializeField] private UdonclHelloDispatchBinding binding;
        [SerializeField] private float input = 3.0f;
        [SerializeField] private float result;
        [SerializeField] private int status;
        private float[] output;

        public override void Interact()
        {
            Run();
        }

        public void Run()
        {
            if (binding == null)
            {
                status = UdonclHelloDispatchBinding.StatusNotInitialized;
                return;
            }
            output = new float[1];
            status = binding.TryDispatchSquare(input);
            if (status != UdonclHelloDispatchBinding.StatusSuccess)
                return;
            status = binding.StartReadOutput(output, this, ""OnReadbackComplete"");
        }

        public void OnReadbackComplete()
        {
            status = binding.GetLastReadbackStatus();
            if (status == UdonclHelloDispatchBinding.StatusSuccess)
                result = output[0];
        }
    }
}
";

        private const string SaxpySource =
            @"// <auto-generated />
using UdonSharp;
using UnityEngine;
using VRC.SDKBase;

namespace Lemolatoon.Udoncl.Generated
{
    [UdonBehaviourSyncMode(BehaviourSyncMode.None)]
    public sealed class UdonclSaxpyDemoExample : UdonSharpBehaviour
    {
        [SerializeField] private UdonclSaxpyDemoBinding binding;
        [SerializeField] private int count = 16;
        [SerializeField] private float alpha = 2.0f;
        [SerializeField] private float firstResult;
        [SerializeField] private int status;
        private float[] input;
        private float[] output;

        public override void Interact()
        {
            Run();
        }

        public void Run()
        {
            if (binding == null)
            {
                status = UdonclSaxpyDemoBinding.StatusNotInitialized;
                return;
            }
            input = new float[32];
            output = new float[32];
            for (int index = 0; index < 16; ++index)
            {
                input[index] = index + 1;
                input[index + 16] = 100 + index;
            }
            status = binding.TryWriteInput(input);
            if (status != UdonclSaxpyDemoBinding.StatusSuccess)
                return;
            status = binding.TryRunSaxpy(count, alpha);
            if (status != UdonclSaxpyDemoBinding.StatusSuccess)
                return;
            status = binding.StartReadOutput(output, this, ""OnReadbackComplete"");
        }

        public void OnReadbackComplete()
        {
            status = binding.GetLastReadbackStatus();
            if (status == UdonclSaxpyDemoBinding.StatusSuccess)
                firstResult = output[0];
        }
    }
}
";
    }
}
