using System;

namespace Lemolatoon.Udoncl.Editor
{
    internal sealed class PackagedExampleUsage
    {
        public PackagedExampleUsage(string className, string source)
        {
            ClassName = className;
            Source = source;
        }

        public string ClassName { get; }
        public string Source { get; }
    }

    internal static class PackagedExampleUsageGenerator
    {
        internal static PackagedExampleUsage ForProgram(string programName)
        {
            switch (programName)
            {
                case "saxpy_demo":
                    return new PackagedExampleUsage("UdonclSaxpyDemoExample", SaxpySource);
                case "udonblas_sgemm_m1n10k144":
                    return new PackagedExampleUsage(
                        "UdonclUdonBlasSgemmExample",
                        UdonBlasSgemmSource
                    );
                default:
                    return null;
            }
        }

        private const string SaxpySource =
            @"// <auto-generated />
using UdonSharp;
using UnityEngine;
using VRC.SDKBase;

namespace Lemolatoon.Udoncl.Generated
{
    [UdonBehaviourSyncMode(BehaviourSyncMode.None)]
    public sealed class UdonclSaxpyDemoExample : UdonSharpBehaviour
    {
        [SerializeField] private UdonclSaxpyDemoBinding binding;
        [SerializeField] private int count = 16;
        [SerializeField] private float alpha = 2.0f;
        [SerializeField] private float firstResult;
        [SerializeField] private int status;
        [SerializeField] private int openclStatus;
        private float[] x;
        private float[] y;
        private float[] result;

        public override void Interact()
        {
            Run();
        }

        public void Run()
        {
            if (binding == null)
            {
                status = UdonclSaxpyDemoBinding.StatusNotInitialized;
                return;
            }
            x = new float[32];
            y = new float[32];
            result = new float[32];
            for (int index = 0; index < 32; ++index)
            {
                x[index] = index + 1;
                y[index] = 100 + index;
            }
            status = binding.TryWriteX(x);
            if (status != UdonclSaxpyDemoBinding.StatusSuccess)
                return;
            status = binding.TryWriteY(y);
            if (status != UdonclSaxpyDemoBinding.StatusSuccess)
                return;
            status = binding.StartRunSaxpy(count, alpha, this, ""OnSaxpyComplete"");
        }

        public void OnSaxpyComplete()
        {
            status = binding.GetRunSaxpyStatus();
            if (status != UdonclSaxpyDemoBinding.StatusSuccess)
                return;
            status = binding.TryGetRunSaxpyResult(out openclStatus);
            if (status != UdonclSaxpyDemoBinding.StatusSuccess || openclStatus != 0)
                return;
            status = binding.StartReadResult(result, this, ""OnReadbackComplete"");
        }

        public void OnReadbackComplete()
        {
            status = binding.GetLastReadbackStatus();
            if (status == UdonclSaxpyDemoBinding.StatusSuccess)
                firstResult = result[0];
        }
    }
}
";

        private const string UdonBlasSgemmSource =
            @"// <auto-generated />
using UdonSharp;
using UnityEngine;
using VRC.SDKBase;

namespace Lemolatoon.Udoncl.Generated
{
    [UdonBehaviourSyncMode(BehaviourSyncMode.None)]
    public sealed class UdonclUdonBlasSgemmExample : UdonSharpBehaviour
    {
        [SerializeField] private UdonclUdonblasSgemmM1n10k144Binding binding;
        [SerializeField] private float[] results;
        [SerializeField] private float maximumError;
        [SerializeField] private int status;
        [SerializeField] private int libraryStatus;
        [SerializeField] private int libraryPhase;
        [SerializeField] private bool completed;

        public override void Interact()
        {
            Run();
        }

        public void Run()
        {
            completed = false;
            maximumError = 0.0f;
            results = new float[10];
            if (binding == null)
            {
                status = UdonclUdonblasSgemmM1n10k144Binding.StatusNotInitialized;
                return;
            }
            status = binding.StartRunUdonBlasSgemm(this, ""OnSgemmComplete"");
        }

        public void OnSgemmComplete()
        {
            status = binding.GetRunUdonBlasSgemmStatus();
            if (status != UdonclUdonblasSgemmM1n10k144Binding.StatusSuccess)
                return;
            status = binding.TryGetRunUdonBlasSgemmResult(out libraryStatus);
            if (status != UdonclUdonblasSgemmM1n10k144Binding.StatusSuccess)
                return;
            status = binding.TryGetUdonBlasSgemmPhase(out libraryPhase);
            if (status != UdonclUdonblasSgemmM1n10k144Binding.StatusSuccess)
                return;
            completed = true;
            if (libraryStatus != 0)
                return;
            for (int column = 0; column < 10; ++column)
            {
                float value;
                status = binding.TryGetUdonBlasSgemmResult(column, out value);
                if (status != UdonclUdonblasSgemmM1n10k144Binding.StatusSuccess)
                    return;
                results[column] = value;
                maximumError = Mathf.Max(
                    maximumError,
                    Mathf.Abs(value - 1224.0f * (column + 1))
                );
            }
        }
    }
}
";
    }
}
